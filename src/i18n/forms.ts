function opts(rows: readonly (Record<string, string> & { value: string })[], locale: Locale) {
  return rows.map((row) => ({ value: row.value, label: row[locale] || row.en }));
}

export function getInquiryForm(locale: Locale) {
  const l = LABELS[locale];
  const inputs: Input[] = [
    { type: 'select', name: 'company', label: l.company, placeholder: l.select, required: true, options: opts(COMPANY, locale) },
    { type: 'select', name: 'channel', label: l.channel, placeholder: l.select, required: true, options: opts(CHANNEL, locale) },
    { type: 'select', name: 'volume', label: l.volume, placeholder: l.select, required: true, options: opts(VOLUME, locale) },
    { type: 'text', name: 'name', label: l.name, placeholder: l.namePh },
    { type: 'email', name: 'email', label: l.email, placeholder: 'you@company.com' },
  ];
  const textarea: Textarea = { label: l.message, name: 'message', placeholder: l.messagePh, rows: 3 };
  const disclaimer: Disclaimer = { label: l.disclaimer };
  return {
    inputs,
    textarea,
    disclaimer,
    button: l.button,
    description: l.description,
    close: l.close,
    preferChat: l.preferChat,
    waLink: l.waTitle,
    waLead: {
      inputs,
      textarea: { ...textarea, rows: 2 },
      disclaimer: { label: l.waDisc },
      button: l.waBtn,
      description: l.waDesc,
      title: l.waTitle,
      subtitle: l.waSub,
    },
  };
}
